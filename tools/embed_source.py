#!/usr/bin/env python3
"""Generate a translation unit embedding a source file as a raw string.

Usage: embed_source.py <input-file> <output-file> <symbol-name>
Deliberately dependency-free; runs at build time from a CMake custom
command. The NALANG delimiter cannot appear in .n sources (validated by
the assertion below), so raw-string folding is safe.
"""
import sys
from pathlib import Path

def main() -> int:
    src, dst, symbol = sys.argv[1], sys.argv[2], sys.argv[3]
    text = Path(src).read_text(encoding="utf-8")
    assert ")NALANG(" not in text, "delimiter collision in embedded source"
    unit = (
        "//Generated by tools/embed_source.py from stdlib/builtins.n — "
        "do not edit.\n"
        f'namespace nlang {{\nconst char* {symbol} = R"NALANG({text})NALANG";\n'
       "} //namespace nlang\n"
    )
    Path(dst).write_text(unit, encoding="utf-8")
    return 0

if __name__ == "__main__":
    sys.exit(main())
